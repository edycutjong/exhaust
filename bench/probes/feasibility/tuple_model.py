"""Probe: a small tuple model of the escrow, written separately from the Fe code (stdlib only).

Prints, per capacity: reachable states, accepted edges, attempts (states x 5) and the labeled-edge hash
h = (h*1000003 + ((enc(s)*5 + a)*42592 + enc(s'))) mod (2^61 - 1), with enc the radix-22 encoding.
With --table C it writes a Fe test module comparing step() with every (state, action) attempt at capacity C.
"""
import sys
from collections import deque

W = 22
SIZE = 4 * W ** 3
M = 2 ** 61 - 1
P = 1000003


def enc(t):
    p, e, s, b = t
    return ((p * W + e) * W + s) * W + b


def step(t, a, cap):
    """Phases 0 Open, 1 Locked, 2 Disputed, 3 Settled; actions 0 Deposit .. 4 Dispute. None = rejected."""
    p, e, s, b = t
    if a == 0:
        return (0, e + 1, s, b) if p == 0 and e + s + b < cap else None
    if a == 1:
        return (1, e, s, b) if p == 0 and e > 0 else None
    if a == 2:
        return (3 if e == 1 else 1, e - 1, s + 1, b) if p == 1 and e > 0 and b == 0 else None
    if a == 3:
        return (3 if e == 1 else p, e - 1, s, b + 1) if p in (1, 2) and e > 0 and s == 0 else None
    return (2, e, s, b) if p == 1 and s == 0 else None


def bfs(cap):
    start = (0, 0, 0, 0)
    seen, q, h, edges, rows = {start}, deque([start]), 0, 0, []
    while q:
        t = q.popleft()
        for a in range(5):
            n = step(t, a, cap)
            rows.append((t, a, n))
            if n is None:
                continue
            edges += 1
            h = (h * P + ((enc(t) * 5 + a) * SIZE + enc(n))) % M
            if n not in seen:
                seen.add(n)
                q.append(n)
    return len(seen), edges, len(rows), h, rows


def pack(t):
    return (t[0] << 24) | (t[1] << 16) | (t[2] << 8) | t[3]


def table(cap, path):
    rows = bfs(cap)[4]
    ins = ", ".join(str(pack(t) * 8 + a) for t, a, _ in rows)
    oks = ", ".join("1" if n else "0" for _, _, n in rows)
    outs = ", ".join(str(pack(n if n else t)) for t, _, n in rows)
    src = f"""// Generated by bench/probes/feasibility/tuple_model.py --table {cap}. Scratch copy only.
use ingot::escrow::{{State, step, action_of, phase_of, phase_id}}

const ROWS: usize = {len(rows)}
const IN: [u32; ROWS] = [{ins}]
const OKS: [u32; ROWS] = [{oks}]
const OUT: [u32; ROWS] = [{outs}]

fn unpack(_ v: u32) -> State {{
    State {{ phase: phase_of(v >> 24), escrow: (v >> 16) & 255, seller: (v >> 8) & 255, buyer: v & 255 }}
}}

fn pack(_ s: State) -> u32 {{
    (phase_id(s.phase) << 24) | (s.escrow << 16) | (s.seller << 8) | s.buyer
}}

#[test]
fn test_probe_oracle_edges() {{
    var i: usize = 0
    while i < ROWS {{
        let n = step(unpack(IN[i] / 8), action_of(IN[i] % 8), {cap})
        assert!((if n.ok {{ 1 }} else {{ 0 }}) == OKS[i])
        assert!(pack(n.s) == OUT[i])
        i += 1
    }}
}}
"""
    open(path, "w").write(src)
    return len(rows)


if __name__ == "__main__":
    if sys.argv[1] == "--table":
        print(table(int(sys.argv[2]), sys.argv[3]))
    else:
        print("cap states edges attempts edge_hash")
        for c in map(int, sys.argv[1:]):
            n, e, att, h, _ = bfs(c)
            print(c, n, e, att, h)
